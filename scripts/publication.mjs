import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { dump, load } from "js-yaml";

export const projectRoot = fileURLToPath(new URL("../", import.meta.url));

export function draftFiles(articles) {
  const drafts = new Set();
  const seen = new Set();
  for (const article of articles) {
    if (typeof article.file !== "string" || !article.file.startsWith("content/") || article.file.split("/").includes("..")) {
      throw new Error(`Invalid article file: ${article.file}`);
    }
    if (seen.has(article.file)) throw new Error(`Duplicate article: ${article.file}`);
    seen.add(article.file);
    if (![undefined, "draft", "published"].includes(article.status)) {
      throw new Error(`Unknown status for ${article.file}: use "draft" or "published".`);
    }
    if (article.status === "draft") drafts.add(article.file);
  }
  return drafts;
}

export function publicNavigation(entries, drafts) {
  return entries.flatMap((entry) => {
    if (entry.pattern) throw new Error("Use explicit file entries in metadata/navigation.yml so draft filtering is unambiguous.");
    const children = entry.children ? publicNavigation(entry.children, drafts) : [];
    // Promote published children when their parent article is a draft.
    if (entry.file && drafts.has(entry.file)) return children;
    if (!entry.file && !entry.url && !children.length) return [];
    const output = { ...entry };
    if (entry.children) output.children = children;
    return [output];
  });
}

export function publicationConfig(root = projectRoot) {
  const editorial = JSON.parse(readFileSync(resolve(root, "metadata/homepage.json"), "utf8"));
  const drafts = draftFiles(editorial.articles);
  const navigation = load(readFileSync(resolve(root, "metadata/navigation.yml"), "utf8"));
  return { version: 1, project: { toc: publicNavigation(navigation.toc, drafts), exclude: [...drafts].sort() } };
}

export function preparePublication(root = projectRoot) {
  const config = publicationConfig(root);
  const destination = resolve(root, "metadata/published.yml");
  const output = "# Generated by npm run publication. Edit article status in metadata/homepage.json.\n" + dump(config, { lineWidth: -1 });
  const changed = !existsSync(destination) || readFileSync(destination, "utf8") !== output;
  if (changed) {
    // These folders contain only generated web output. Clearing them also
    // removes old routes, search entries, and downloadable copies of new drafts.
    for (const directory of ["_build/site", "_build/html"]) rmSync(resolve(root, directory), { recursive: true, force: true });
    writeFileSync(destination, output);
  }
  return { config, changed };
}

export function assertPublicationCurrent(root = projectRoot) {
  const destination = resolve(root, "metadata/published.yml");
  if (!existsSync(destination) || JSON.stringify(load(readFileSync(destination, "utf8"))) !== JSON.stringify(publicationConfig(root))) {
    throw new Error("Publication status changed. Run make prepare-publication, then restart the preview or rebuild the site.");
  }
}

export function assertNotDraft(file, root = projectRoot) {
  const config = publicationConfig(root);
  if (config.project.exclude.some((draft) => resolve(root, draft) === resolve(file))) {
    throw new Error(`Cannot publish or include draft article: ${file}`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { config, changed } = preparePublication();
  console.log(`Publication configured: ${config.project.exclude.length} drafts excluded.${changed ? " Cleared stale web output." : ""}`);
}
